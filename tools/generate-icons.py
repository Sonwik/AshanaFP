"""Regenerates src/Ashana.UI/IconShapes.g.cs from the Lucide icon set (https://lucide.dev, ISC licence).

Usage:
    npm pack lucide-static@1.64.0 && tar -xzf lucide-static-1.64.0.tgz
    python3 tools/generate-icons.py package/icons

Add a name to ICONS below, run the script, rebuild. Only the icons listed here end up in the app.
"""
import pathlib
import re
import sys

ICONS = """
shopping-bag utensils-crossed chef-hat clock check x plus minus trash-2 search sun moon bell bell-ring
chart-column settings users user log-out log-in menu chevron-right chevron-left chevron-down circle-alert info
triangle-alert pause play receipt monitor list-checks pencil archive rotate-ccw download leaf flame sparkles timer
hand-platter soup coffee history tv package-check circle-check-big wifi-off refresh-cw eye eye-off store
layout-dashboard square-pen ban badge-check credit-card banknote qr-code message-square-text circle-help
arrow-left volume-2 volume-x lock funnel shield-check mail key-round user-plus smartphone calendar-clock
external-link wifi save tag
""".split()

def main(icon_dir: str) -> None:
    root = pathlib.Path(__file__).resolve().parents[1]
    entries, missing = [], []
    for name in ICONS:
        path = pathlib.Path(icon_dir) / f"{name}.svg"
        if not path.exists():
            missing.append(name)
            continue
        svg = re.sub(r"<!--.*?-->", "", path.read_text(encoding="utf-8"), flags=re.S)
        inner = re.search(r">\s*(.*)\s*</svg>", svg, re.S).group(1)
        inner = re.sub(r"\s+", " ", inner).replace('" />', '"/>').strip().replace('"', '\\"')
        entries.append(f'        ["{name}"] = "{inner}",')
    if missing:
        sys.exit("Missing icons: " + ", ".join(missing))
    body = "\n".join(entries)
    code = f'''// <auto-generated>
// Icon shapes from Lucide (https://lucide.dev), ISC License. See THIRD-PARTY-NOTICES.md.
// Regenerate with tools/generate-icons.py if you add icons.
// </auto-generated>
using System.Collections.Frozen;

namespace Ashana.UI;

/// <summary>Inner SVG markup of every icon the app uses (24×24 viewBox, stroke = currentColor).</summary>
internal static class IconShapes
{{
    public static readonly FrozenDictionary<string, string> All = new Dictionary<string, string>(System.StringComparer.Ordinal)
    {{
{body}
    }}.ToFrozenDictionary(System.StringComparer.Ordinal);
}}
'''
    out = root / "src" / "Ashana.UI" / "IconShapes.g.cs"
    out.write_text(code, encoding="utf-8")
    print(f"{len(entries)} icons written to {out}")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "package/icons")
